// Generates src/theme/tokens.generated.ts from the SPA's design tokens (src/SlideWorks.Client/src/theme/tokens.css),
// so the app and the web share one source. Run `pnpm run tokens` after tokens.css changes; tokens.test.ts fails
// while the committed file is stale. Kept: colours (hex) and sizes (px, as numbers). Left out: font stacks,
// gradients and shadows, which React Native can't take as CSS strings.
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

export const tokensCssPath = fileURLToPath(
  new URL('../../SlideWorks.Client/src/theme/tokens.css', import.meta.url),
);
export const generatedPath = fileURLToPath(
  new URL('../src/theme/tokens.generated.ts', import.meta.url),
);

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

export function generateTokens(css) {
  const root = css.slice(css.indexOf(':root'));
  const body = root.slice(root.indexOf('{') + 1, root.indexOf('\n}'));
  const withoutComments = body.replace(/\/\*[\s\S]*?\*\//g, '');
  const raw = new Map();
  for (const match of withoutComments.matchAll(/--sw-([a-z0-9-]+)\s*:\s*([^;]+);/g)) {
    raw.set(match[1], match[2].trim().replace(/\s+/g, ' '));
  }
  const resolve = (value, seen = new Set()) => {
    const ref = /^var\(--sw-([a-z0-9-]+)\)$/.exec(value);
    if (!ref || seen.has(ref[1]) || !raw.has(ref[1])) return value;
    return resolve(raw.get(ref[1]), new Set([...seen, ref[1]]));
  };
  const lines = [];
  for (const [name, value] of raw) {
    const resolved = resolve(value);
    if (/^#[0-9a-f]{3,8}$/i.test(resolved))
      lines.push(`  ${camel(name)}: '${resolved.toLowerCase()}',`);
    else if (/^\d+(\.\d+)?px$/.test(resolved))
      lines.push(`  ${camel(name)}: ${parseFloat(resolved)},`);
  }
  return [
    '// Generated by scripts/generate-tokens.mjs from src/SlideWorks.Client/src/theme/tokens.css. Do not edit by hand:',
    '// run `pnpm run tokens`.',
    'export const tokens = {',
    ...lines,
    '} as const;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(generatedPath, generateTokens(readFileSync(tokensCssPath, 'utf8')));
}
