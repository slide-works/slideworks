export type IconName = keyof typeof ICONS;

// The drawing for a name, or undefined when the set has no such icon.
export function iconFor(name: string): LucideIcon | undefined {
  return Object.hasOwn(ICONS, name) ? ICONS[name as IconName] : undefined;
}
