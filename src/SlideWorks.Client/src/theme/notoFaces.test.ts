// @vitest-environment node
import { describe, expect, it } from 'vitest';

// notoFaces.css is generated from the @fontsource Noto packages' 400 and 700 CSS by the first test below.
// Regenerate it after bumping one of those packages:
//   UPDATE_NOTO_FACES=1 pnpm exec vitest run src/theme/notoFaces.test.ts
// Each face keeps only its own script's code points, so Latin, digits, punctuation and symbols the template font
// lacks still fall to system-ui, as before the Noto fallbacks. Only woff2 files are referenced.

// Vitest empties CSS imports, so the files are read from disk (as slidesUseTokens.test.ts does). The client has no
// Node types, hence the calls typed here.
interface Fs {
  readFileSync(path: URL, encoding: 'utf8'): string;
  writeFileSync(path: URL, data: string): void;
}
const nodeProcess = (
  globalThis as unknown as {
    process: { getBuiltinModule(id: 'node:fs'): Fs; env: Record<string, string | undefined> };
  }
).process;
const fs = nodeProcess.getBuiltinModule('node:fs');

type Range = readonly [number, number];

const CJK: Range[] = [
  [0x2e80, 0x2fdf], // radicals, Kangxi
  [0x2ff0, 0x2fff], // ideographic description
  [0x3000, 0x303f], // CJK symbols and punctuation
  [0x3190, 0x319f], // kanbun
  [0x31c0, 0x31ef], // strokes
  [0x3200, 0x33ff], // enclosed CJK letters, CJK compatibility
  [0x3400, 0x4dbf], // extension A
  [0x4e00, 0x9fff], // unified ideographs
  [0xf900, 0xfaff], // compatibility ideographs
  [0xfe30, 0xfe4f], // CJK compatibility forms
  [0xff00, 0xffef], // halfwidth and fullwidth forms
  [0x20000, 0x3ffff], // extensions B onwards
];

// Family order and names are the stack's (lookStyle.ts, tokens.css).
const FAMILIES: { pkg: string; ranges: Range[] }[] = [
  { pkg: 'noto-sans-thai', ranges: [[0x0e00, 0x0e7f]] },
  {
    pkg: 'noto-sans-jp',
    ranges: [
      ...CJK,
      [0x3040, 0x30ff], // hiragana, katakana
      [0x31f0, 0x31ff], // katakana phonetic extensions
      [0x1b000, 0x1b16f], // kana supplement and extended
      [0x1f200, 0x1f2ff], // enclosed ideographic supplement
    ],
  },
  {
    pkg: 'noto-sans-kr',
    ranges: [
      [0x1100, 0x11ff], // Hangul Jamo
      [0x3130, 0x318f], // compatibility Jamo
      [0xa960, 0xa97f], // Jamo extended A
      [0xac00, 0xd7ff], // syllables, Jamo extended B
      [0xffa0, 0xffdf], // halfwidth Hangul
    ],
  },
  { pkg: 'noto-sans-sc', ranges: [...CJK, [0x3100, 0x312f], [0x31a0, 0x31bf]] },
  { pkg: 'noto-sans-tc', ranges: [...CJK, [0x3100, 0x312f], [0x31a0, 0x31bf]] },
];
const WEIGHTS = [400, 700];

const parseRanges = (unicodeRange: string): Range[] =>
  unicodeRange.split(',').map((part) => {
    const [from, to = from] = part.trim().replace(/^U\+/i, '').split('-');
    return [parseInt(from, 16), parseInt(to, 16)];
  });

const clip = (ranges: Range[], allowed: Range[]): Range[] =>
  ranges
    .flatMap(([from, to]) =>
      allowed
        .filter(([a, b]) => a <= to && b >= from)
        .map(([a, b]): Range => [Math.max(a, from), Math.min(b, to)]),
    )
    .sort((x, y) => x[0] - y[0])
    .reduce<Range[]>((merged, range) => {
      const last = merged.at(-1);
      if (last && range[0] <= last[1] + 1)
        merged[merged.length - 1] = [last[0], Math.max(last[1], range[1])];
      else merged.push(range);
      return merged;
    }, []);

const hex = (n: number) => n.toString(16);
const formatRanges = (ranges: Range[]) =>
  ranges.map(([a, b]) => (a === b ? `U+${hex(a)}` : `U+${hex(a)}-${hex(b)}`)).join(',');

const FACE =
  /@font-face\s*{[^}]*?font-family:\s*'([^']+)';[^}]*?url\(\.\/files\/([^)]+?\.woff2)\)[^}]*?unicode-range:\s*([^;]+);[^}]*}/g;

function generate(): string {
  const faces = FAMILIES.flatMap(({ pkg, ranges }) =>
    WEIGHTS.flatMap((weight) => {
      const css = fs.readFileSync(
        new URL(`../../node_modules/@fontsource/${pkg}/${weight}.css`, import.meta.url),
        'utf8',
      );
      return [...css.matchAll(FACE)].flatMap(([, family, file, unicodeRange]) => {
        const kept = clip(parseRanges(unicodeRange), ranges);
        return kept.length === 0
          ? []
          : [
              `@font-face {\n  font-family: '${family}';\n  font-style: normal;\n  font-display: swap;\n` +
                `  font-weight: ${weight};\n  src: url('@fontsource/${pkg}/files/${file}') format('woff2');\n` +
                `  unicode-range: ${formatRanges(kept)};\n}\n`,
            ];
      });
    }),
  );
  return (
    '/* Generated by notoFaces.test.ts from @fontsource 400 and 700; do not edit. Each face claims only its own\n' +
    '   script, so Latin, digits, punctuation and symbols fall to system-ui. */\n' +
    faces.join('')
  );
}

const committedUrl = new URL('./notoFaces.css', import.meta.url);

describe('notoFaces.css', () => {
  it('notoFaces_WhenGenerated_ShouldMatchCommittedFile', () => {
    const generated = generate();
    if (nodeProcess.env.UPDATE_NOTO_FACES === '1') fs.writeFileSync(committedUrl, generated);
    expect(fs.readFileSync(committedUrl, 'utf8')).toBe(generated);
  });

  it('notoFaces_WhenAnyFace_ShouldClaimNoLatinPunctuationOrSymbols', () => {
    const css = fs.readFileSync(committedUrl, 'utf8');
    const claimed = [...css.matchAll(/unicode-range:\s*([^;]+);/g)].flatMap(([, r]) =>
      parseRanges(r),
    );
    // Basic Latin to Cyrillic and Greek, Latin Extended Additional, general punctuation to dingbats.
    const latinAndSymbols: Range[] = [
      [0x0000, 0x052f],
      [0x1e00, 0x1fff],
      [0x2000, 0x2bff],
    ];
    expect(clip(claimed, latinAndSymbols)).toEqual([]);
  });

  it('notoFaces_WhenGenerated_ShouldHaveBothWeightsOfEveryFamily', () => {
    const css = fs.readFileSync(committedUrl, 'utf8');
    const pairs = new Set(
      [...css.matchAll(/font-family: '([^']+)';[^}]*?font-weight: (\d+);/g)].map(
        ([, f, w]) => `${f} ${w}`,
      ),
    );
    const families = [
      'Noto Sans Thai',
      'Noto Sans JP',
      'Noto Sans KR',
      'Noto Sans SC',
      'Noto Sans TC',
    ];
    expect([...pairs].sort()).toEqual(
      families.flatMap((f) => WEIGHTS.map((w) => `${f} ${w}`)).sort(),
    );
  });
});
